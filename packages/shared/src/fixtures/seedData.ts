interface RawSeedOrderSpec {
  id: string;
  sheetRowNumber: number;
  date: string;
  customerName: string;
  phone: string;
  contextOrRelay: string;
  harvestLabel: string;
  jars: Record<string, number>;
  manualOverride?: number | null;
  orderStatus: OrderStatus;
  paymentStatus: PaymentStatus;
  collectedByThirdParty: boolean;
  collectorName: string;
  transferStatus: TransferStatus;
  notes?: string;
}

function buildSeedOrder(spec: RawSeedOrderSpec): SaleOrder {
  const harvest = SEED_HARVESTS.find((h) => h.label === spec.harvestLabel);
  const itemsInput = Object.entries(spec.jars).map(([formatCode, quantity]) => ({
    formatCode,
    quantity,
  }));
  const totals = computeOrderTotals(
    itemsInput,
    harvest,
    SEED_JAR_FORMATS,
    spec.paymentStatus,
    spec.manualOverride ?? null,
  );
  const transfer = normalizeOrderTransferState(
    spec.paymentStatus,
    spec.collectedByThirdParty,
    spec.collectorName,
    spec.transferStatus,
    null,
  );

  return {
    id: spec.id,
    sheetRowNumber: spec.sheetRowNumber,
    date: spec.date,
    customerName: spec.customerName,
    phone: spec.phone,
    contextOrRelay: spec.contextOrRelay,
    harvestLabel: spec.harvestLabel,
    items: totals.items,
    computedWeightKg: totals.computedWeightKg,
    computedAmountEur: totals.computedAmountEur,
    manualAmountOverrideEur: totals.manualAmountOverrideEur,
    effectiveAmountEur: totals.effectiveAmountEur,
    orderStatus: spec.orderStatus,
    paymentStatus: spec.paymentStatus,
    collectedByThirdParty: transfer.collectedByThirdParty,
    collectorName: transfer.collectorName,
    transferStatus: transfer.transferStatus,
    notes: spec.notes,
    updatedAt: `${spec.date}T10:00:00.000Z`,
  };
}

